class Projection:
    def __init__(self, label, template=None, lat_range=None):
        self.label, self.template, self.lat_range = label, template, lat_range
        self.native = template is None
        self.fwd = self.inv = None

    def setup(self, lon, lat):
        if self.native:
            return
        lo0, lo1 = float(np.nanmin(lon)), float(np.nanmax(lon))
        la0, la1 = float(np.nanmin(lat)), float(np.nanmax(lat))
        lon0, lat0 = (lo0 + lo1) / 2, (la0 + la1) / 2
        span = la1 - la0
        lat1, lat2 = la0 + span / 6, la1 - span / 6
        if abs(lat1 + lat2) < 1e-6:          # conic projections reject symmetric parallels
            lat2 += 1.0
        params = dict(lon0=lon0, lat0=lat0, lat1=lat1, lat2=lat2,
                      zone=int(((lon0 + 180) % 360) // 6) + 1, south="+south" if lat0 < 0 else "")
        crs = CRS.from_proj4(self.template.format(**params))
        self.fwd = Transformer.from_crs("EPSG:4326", crs, always_xy=True)
        self.inv = Transformer.from_crs(crs, "EPSG:4326", always_xy=True)

    def forward(self, lon, lat):
        """lon/lat (deg) -> x/y (km). Non-representable points become NaN."""
        if self.native:
            return lon, lat
        lon = np.asarray(lon, dtype=float)
        lat = np.asarray(lat, dtype=float)
        if self.lat_range is not None:
            lat = np.where((lat >= self.lat_range[0]) & (lat <= self.lat_range[1]), lat, np.nan)
        with np.errstate(all="ignore"):
            x, y = self.fwd.transform(lon, lat)
            x, y = np.asarray(x, dtype=float) / 1000.0, np.asarray(y, dtype=float) / 1000.0
            bad = ~(np.isfinite(x) & np.isfinite(y)) | (np.abs(x) > 5e4) | (np.abs(y) > 5e4)
        x = np.where(bad, np.nan, x)
        y = np.where(bad, np.nan, y)
        return x, y

    def inverse(self, x, y):
        """x/y (km) -> lon/lat (deg)."""
        if self.native:
            return x, y
        with np.errstate(all="ignore"):
            lon, lat = self.inv.transform(np.asarray(x, dtype=float) * 1000.0,
                                          np.asarray(y, dtype=float) * 1000.0)
        lon = np.asarray(lon, dtype=float)
        lat = np.asarray(lat, dtype=float)
        bad = ~(np.isfinite(lon) & np.isfinite(lat))
        return np.where(bad, np.nan, lon), np.where(bad, np.nan, lat)


