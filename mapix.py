    # --- selectors ---------------------------------------------------------------
    def activate_selector(self, mode, callback):
        self.deactivate_selector()
        self.selection_callback = callback

        def done(vertices):
            if self.selection_callback:
                self.selection_callback(vertices, mode)

        rect_cb = lambda e1, e2: done([(e1.xdata, e1.ydata), (e2.xdata, e2.ydata)])
        kw = dict(useblit=True, button=[1], minspanx=0, minspany=0, spancoords="data", interactive=True)
        props = dict(facecolor=COL_SELECT, edgecolor=COL_SELECT, alpha=0.25, fill=True)
        cls = {"rectangle": RectangleSelector, "ellipse": EllipseSelector}.get(mode)
        if cls is not None:
            try:
                self.selector = cls(self.ax, rect_cb, props=props, **kw)
            except TypeError:
                self.selector = cls(self.ax, rect_cb, **kw)
        elif mode == "polygon":
            try:
                self.selector = PolygonSelector(self.ax, lambda v: done(v), useblit=True,
                                                props=dict(color=COL_SELECT, linewidth=2))
            except TypeError:
                self.selector = PolygonSelector(self.ax, lambda v: done(v), useblit=True)
        self.draw_idle()

    def deactivate_selector(self):
        if self.selector is not None:
            try:
                self.selector.set_visible(False)
                self.selector.set_active(False)
                self.selector.disconnect_events()
            except Exception:
                pass
            self.selector = None
            self.draw_idle()
        self.selection_callback = None

    # --- mouse -----------------------------------------------------------------------
    def _tool_active(self):
        if self.toolbar is not None and str(getattr(self.toolbar, "mode", "")):
            return True
        return self.selector is not None and self.selector.active

    def _on_press(self, event):
        if event.inaxes != self.ax or event.xdata is None or self._tool_active():
            return
        if event.button == 1 and self.click_callback and self.image is not None:
            self.click_callback(event.xdata, event.ydata)
        elif event.button in (2, 3):
            self._pan = (event.x, event.y, self.ax.get_xlim(), self.ax.get_ylim())

    def _on_release(self, event):
        self._pan = None

    def _on_motion(self, event):
        if self._pan is not None and event.x is not None:
            x0, y0, xl, yl = self._pan
            bb = self.ax.bbox
            dx = (event.x - x0) / bb.width * (xl[1] - xl[0])
            dy = (event.y - y0) / bb.height * (yl[1] - yl[0])
            self.ax.set_xlim(xl[0] - dx, xl[1] - dx)
            self.ax.set_ylim(yl[0] - dy, yl[1] - dy)
            self.draw_idle()
            return
        if self.hover_callback is not None:
            if event.inaxes == self.ax and event.xdata is not None:
                self.hover_callback(event.xdata, event.ydata)
            else:
                self.hover_callback(None, None)

    def _on_scroll(self, event):
        if event.inaxes != self.ax or event.xdata is None or self.image is None:
            return
        f = 0.8 if event.button == "up" else 1.25
        xl, yl = self.ax.get_xlim(), self.ax.get_ylim()
        x, y = event.xdata, event.ydata
        self.ax.set_xlim(x - (x - xl[0]) * f, x + (xl[1] - x) * f)
        self.ax.set_ylim(y - (y - yl[0]) * f, y + (yl[1] - y) * f)
        self.draw_idle()


