    def calculate_and_show_profile(self):
        (lon1, lat1), (lon2, lat2) = self.profile_points[:2]
        c1, c2 = int(self.lon_ax.idx(lon1)), int(self.lon_ax.idx(lon2))
        r1, r2 = int(self.lat_ax.idx(lat1)), int(self.lat_ax.idx(lat2))
        n = max(2, int(max(abs(r2 - r1), abs(c2 - c1)) * 2) + 1)
        lons = np.linspace(lon1, lon2, n)
        lats = np.linspace(lat1, lat2, n)
        rows = np.asarray(self.lat_ax.idx(lats), dtype=int)
        cols = np.asarray(self.lon_ax.idx(lons), dtype=int)
        phi, lam = np.deg2rad(lats), np.deg2rad(lons)
        a = np.sin(np.diff(phi) / 2) ** 2 + np.cos(phi[:-1]) * np.cos(phi[1:]) * np.sin(np.diff(lam) / 2) ** 2
        seg = 2 * EARTH_KM * np.arcsin(np.sqrt(np.clip(a, 0, 1)))
        self.last_profile = {
            "distance_km": np.concatenate(([0.0], np.cumsum(seg))),
            "longitude": lons, "latitude": lats,
            "value_m": np.asarray(self.data[rows, cols], dtype=float),
            "row": rows, "column": cols,
        }
        self.draw_profile_line()
        self.refresh_profile(keep_view=False)
        self.profile_window.show()
        self.profile_window.raise_()
        self.update_enabled()

