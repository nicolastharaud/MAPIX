def find_internal_oceans(data, wrap_lon=False):
    """Mask of negative cells (4-neighbour connectivity) NOT connected to the main ocean.

    Main ocean = largest connected region of cells < 0.
    Grid borders are not physical: with `wrap_lon` the left/right edges join
    (globe); otherwise any negative region touching a border is considered open.
    """
    from scipy import ndimage
    with np.errstate(invalid="ignore"):
        ocean = data < 0
    if not ocean.any():
        return np.zeros(data.shape, dtype=bool)
    lab, n = ndimage.label(ocean)               # default structure = 4 neighbours
    parent = np.arange(n + 1)

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    if wrap_lon:
        left, right = lab[:, 0], lab[:, -1]
        sel = (left > 0) & (right > 0) & (left != right)
        if sel.any():
            pairs = np.unique(np.column_stack([left[sel], right[sel]]), axis=0)
            for a, b in pairs:
                ra, rb = find(int(a)), find(int(b))
                if ra != rb:
                    parent[rb] = ra
            for i in np.unique(pairs):
                parent[i] = find(int(i))
    counts = np.bincount(lab.ravel(), minlength=n + 1).astype(float)
    counts[0] = 0
    root_sizes = np.bincount(parent, weights=counts, minlength=n + 1)
    main = int(np.argmax(root_sizes))
    edges = [lab[0, :], lab[-1, :]]
    if not wrap_lon:
        edges += [lab[:, 0], lab[:, -1]]
    e = np.unique(np.concatenate(edges))
    e = e[e > 0]
    is_open = np.zeros(n + 1, dtype=bool)
    is_open[parent[e]] = True
    is_open[main] = True
    return ocean & ~is_open[parent[lab]]


def label_zones(flagged):
    """Zones of flagged cells sorted by size: (rows, cols, sizes) of one cell per zone."""
    from scipy import ndimage
    zl, zn = ndimage.label(flagged)
    if zn == 0:
        e = np.zeros(0, dtype=int)
        return e, e, e
    flat = zl.ravel()
    idx = np.flatnonzero(flat)
    labs = flat[idx]
    uniq, first = np.unique(labs, return_index=True)
    sizes = np.bincount(labs)[uniq]
    rows, cols = np.unravel_index(idx[first], flagged.shape)
    order = np.argsort(-sizes)
    return rows[order], cols[order], sizes[order]


