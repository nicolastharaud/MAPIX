def resolve_cmap(name, reverse=False):
    custom_cmaps = {"fes9": fes9_map, "delphi": delphi_map, "ston": ston_map}
    if name in custom_cmaps:
        cm = custom_cmaps[name]
    elif crameri_cm is not None and hasattr(crameri_cm, name):
        if reverse and hasattr(crameri_cm, name + "_r"):
            return getattr(crameri_cm, name + "_r")
        cm = getattr(crameri_cm, name)
    else:
        cm = colormaps[name]
    return cm.reversed() if reverse else cm


