    def open_file(self):
        path, _ = QtWidgets.QFileDialog.getOpenFileName(
            self, "Open NetCDF", "", "NetCDF (*.nc *.nc4 *.cdf);;All files (*)")
        if not path:
            return
        try:
            if self.dataset is not None:
                self.dataset.close()
            self.file_path = Path(path)
            self.dataset = Dataset(path, "r")
            self.var_combo.blockSignals(True)
            self.var_combo.clear()
            candidates = [n for n, v in self.dataset.variables.items() if v.ndim == 2]
            self.var_combo.addItems(candidates)
            self.var_combo.blockSignals(False)
            if not candidates:
                raise ValueError("No 2D variable found")
            preferred = "topobathy" if "topobathy" in candidates else candidates[0]
            self.var_combo.setCurrentText(preferred)
            self.change_variable(preferred)
        except Exception as exc:
            self.show_error(exc)

    def find_axis(self, dim, kind):
        """1-D variable on dimension `dim` that is the lon/lat axis (lon=x=longitude, lat=y=latitude)."""
        best, best_score = None, 0
        for name, var in self.dataset.variables.items():
            if var.ndim == 1 and var.dimensions[0] == dim:
                sc = axis_score(name, var, kind) + (1 if name == dim else 0) * (axis_score(name, var, kind) > 0)
                if sc > best_score:
                    best, best_score = name, sc
        return best

    def change_variable(self, name):
        if not name or self.dataset is None:
            return
        try:
            var = self.dataset.variables[name]
            d0, d1 = var.dimensions
            cand = [(self.find_axis(d0, "lat"), self.find_axis(d1, "lon"), False),
                    (self.find_axis(d0, "lon"), self.find_axis(d1, "lat"), True)]
            lat_name = lon_name = None
            for la, lo, tr in cand:
                if la and lo:
                    lat_name, lon_name, self.transpose = la, lo, tr
                    break
            if lat_name is None:
                raise ValueError("lon/lat axes not found (lon, x, longitude / lat, y, latitude)")
            raw = var[:]
            arr = np.ma.filled(np.ma.asarray(raw), np.nan).astype(np.float64)
            if self.transpose:
                arr = arr.T
            lat = np.asarray(self.dataset.variables[lat_name][:], dtype=float)
            lon = np.asarray(self.dataset.variables[lon_name][:], dtype=float)
            if arr.shape != (lat.size, lon.size):
                raise ValueError("Axis sizes do not match data shape")
            self.variable_name, self.lat_name, self.lon_name = name, lat_name, lon_name
            self.data = np.ascontiguousarray(arr)
            self.original_data = self.data.copy()
            self.lat, self.lon = lat, lon
            self.lat_ax, self.lon_ax = Axis1D(lat), Axis1D(lon)
            self.regular = is_regular(lat) and is_regular(lon)
            self.lon_min = float(np.nanmin(lon))
            dx = float(np.median(np.abs(np.diff(lon)))) if lon.size > 1 else 0.0
            self.wrap_lon = (float(np.nanmax(lon)) - self.lon_min + dx) >= 359.0
            self.show_nan = False
            self.regridded = False
            self.oceans_action.setChecked(False)
            self.oceans_action.setEnabled(False)
            self.oceans_action.setToolTip("Regrid first")
            # reset state
            self.history, self.hist_pos = [], 0
            self.selected_mask = self.outlier_mask = self.ocean_mask = None
            self.outline_ll = None
            self.zones, self.zone_idx = None, -1
            self.current_cell = None
            self.nan_cells = None
            self.nan_idx = -1
            self.last_profile = None
            self.profile_points = []
            self.sel_info.setText("None")
            self.out_info.setText("—")
            self.setWindowTitle(f"Mapix — {self.file_path.name} — {name}")
            self.auto_scale_silent()
            self.setup_projection()
            self.rebuild_view()
            self.update_nan_info()
            self.refresh_history()
            self.update_enabled()
            note = ""
            if np.nanmax(np.abs(lat)) > 90.0001 or np.nanmax(np.abs(lon)) > 360.0001:
                note = "   |   Axes outside degree range: check units"
            self.status.setText(f"{self.data.shape[0]}×{self.data.shape[1]}   lat={lat_name}  lon={lon_name}{note}")
            if self.oceans_on:
                self.compute_oceans()
        except Exception as exc:
            self.show_error(exc)

    def auto_scale_silent(self):
        lo, hi = np.nanmin(self.data), np.nanmax(self.data)
        if not (np.isfinite(lo) and np.isfinite(hi)):
            lo, hi = 0.0, 1.0
        if lo == hi:
            hi = lo + 1.0
        for s, v in ((self.vmin, lo), (self.vmax, hi)):
            s.blockSignals(True)
            s.setValue(float(v))
            s.blockSignals(False)
            s.setSingleStep(max((hi - lo) / 100.0, 0.01))

    # ----------------------------------------------------------- projections --
    def setup_projection(self):
        if self.lon is None:
            return
        try:
            self.proj.setup(self.lon, self.lat)
        except Exception as exc:
            self.proj_combo.blockSignals(True)
            self.proj_combo.setCurrentIndex(0)
            self.proj_combo.blockSignals(False)
            self.proj = self.projections[0]
            self.show_error(f"Projection failed: {exc}")

    def change_projection(self, index):
        self.proj = self.projections[index]
        if self.data is None:
            return
        QtWidgets.QApplication.setOverrideCursor(QtCore.Qt.CursorShape.WaitCursor)
        try:
            self.setup_projection()
            self.rebuild_view()
            if self.canvas.stride > 1:
                self.status.setText(f"Display decimated ×{self.canvas.stride} (edits use full data)")
        finally:
            QtWidgets.QApplication.restoreOverrideCursor()

    def rebuild_view(self):
        if self.data is None:
            return
