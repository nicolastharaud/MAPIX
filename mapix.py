    def auto_scale(self):
        if self.data is None:
            return
        lo, hi = np.nanmin(self.data), np.nanmax(self.data)
        if not (np.isfinite(lo) and np.isfinite(hi)):
            lo, hi = 0.0, 1.0
        if lo == hi:
            hi = lo + 1.0
        for s, v in ((self.vmin, lo), (self.vmax, hi)):
            s.blockSignals(True)
            s.setValue(float(v))
            s.blockSignals(False)
        step = max((hi - lo) / 100.0, 0.01)
        self.vmin.setSingleStep(step)
        self.vmax.setSingleStep(step)
        self.apply_scale()

    def apply_scale(self):
        if self.data is None:
            return
        lo, hi = self.vmin.value(), self.vmax.value()
        if lo >= hi:
            self.status.setText("Min must be below Max")
            return
        self.canvas.set_color_limits(lo, hi)

    # ----------------------------------------------------------- coordinates --
    def to_lonlat(self, x, y):
        if self.proj.native:
            return float(x), float(y)
        lo, la = self.proj.inverse(x, y)
        lo, la = float(lo), float(la)
        if not (np.isfinite(lo) and np.isfinite(la)) or abs(la) > 90:
            return None
        return self.lon_min + ((lo - self.lon_min) % 360.0), la

    def locate(self, x, y):
        ll = self.to_lonlat(x, y)
        if ll is None:
            return None
        lo, la = ll
        if not (self.lon_ax.contains(lo) and self.lat_ax.contains(la)):
            return None
        return int(self.lat_ax.idx(la)), int(self.lon_ax.idx(lo))

    def cell_xy(self, rows, cols):
        return self.proj.forward(self.lon[cols], self.lat[rows])

