    def perform_regrid(self, dlon, dlat, method):
        if not (self.lon_ax.mono and self.lat_ax.mono):
            self.show_error("Regrid needs monotonic lon/lat axes (2 points min)")
            return False
        lo0, lo1 = float(self.lon.min()), float(self.lon.max())
        la0, la1 = float(self.lat.min()), float(self.lat.max())
        nx = int(np.floor((lo1 - lo0) / dlon + 1e-9)) + 1
        ny = int(np.floor((la1 - la0) / dlat + 1e-9)) + 1
        if nx * ny > 50_000_000:
            QtWidgets.QMessageBox.warning(self, "Regrid", f"Too many cells: {nx * ny / 1e6:.0f} M (max 50 M)")
            return False
        lon_new = lo0 + dlon * np.arange(nx)
        lat_new = la0 + dlat * np.arange(ny)
        prog = QtWidgets.QProgressDialog("Regrid", None, 0, 100, self)
        prog.setCancelButton(None)
        prog.setWindowTitle("Regrid")
        prog.setWindowModality(QtCore.Qt.WindowModality.WindowModal)
        prog.setMinimumDuration(0)
        prog.setAutoClose(False)
        prog.setValue(0)

        def step(i, n):
            prog.setValue(int(100 * (i + 1) / n))
            QtWidgets.QApplication.processEvents()

        try:
            out = regrid_array(self.data, self.lon, self.lat, lon_new, lat_new, method, step)
        except Exception as exc:
            prog.close()
            self.show_error(exc)
            return False
        prog.close()
        # the regridded file becomes the new original
        self.lon, self.lat = lon_new, lat_new
        self.lon_ax, self.lat_ax = Axis1D(lon_new), Axis1D(lat_new)
        self.data = np.ascontiguousarray(out)
        self.original_data = self.data.copy()
        self.transpose = False
        self.regular = True
        self.lon_min = lo0
        self.wrap_lon = (float(lon_new.max()) - lo0 + dlon) >= 359.0
        self.history, self.hist_pos = [], 0
        self.selected_mask = self.outlier_mask = self.ocean_mask = None
        self.outline_ll = None
        self.zones, self.zone_idx = None, -1
        self.current_cell = None
        self.last_profile = None
        self.profile_points = []
        self.profile_window.hide()
        self.sel_info.setText("None")
        self.out_info.setText("—")
        self.show_nan = False
        self.nan_cells = None
        self.nan_idx = -1
        self.regridded = True
        self.regrid_info = f"{'Bilinear' if method == 'bilinear' else 'Nearest Neighbor'}, {dlon:g} x {dlat:g} deg"
        self.oceans_action.setEnabled(True)
        self.oceans_action.setToolTip("Highlight negative cells cut off from the main ocean  [6]")
        self.setup_projection()
        self.rebuild_view()
        self.update_nan_info()
        self.refresh_history()
        self.update_enabled()
        if self.oceans_on:
            self.compute_oceans()
        self.status.setText(f"Regrid done   |   {ny}×{nx}   |   step {dlon:g}° × {dlat:g}°")
        return True

    def save_regridded(self, path):
        """New NetCDF: longitude / latitude / topobathy, metadata of the source file kept."""
        src = self.dataset
        var = src.variables[self.variable_name]
        with Dataset(path, "w") as out:
            out.setncatts({k: src.getncattr(k) for k in src.ncattrs()})
            out.setncattr("regrid", self.regrid_info)
            out.createDimension("latitude", self.lat.size)
            out.createDimension("longitude", self.lon.size)
            for new, old, values in (("latitude", self.lat_name, self.lat),
                                     ("longitude", self.lon_name, self.lon)):
                ov = src.variables[old]
                v = out.createVariable(new, "f8", (new,))
                v.setncatts({a: ov.getncattr(a) for a in ov.ncattrs() if a != "_FillValue"})
                v[:] = values
            fill = var.getncattr("_FillValue") if "_FillValue" in var.ncattrs() else None
            v = out.createVariable("topobathy", var.dtype, ("latitude", "longitude"),
                                   zlib=True, fill_value=fill)
            v.setncatts({a: var.getncattr(a) for a in var.ncattrs() if a != "_FillValue"})
            v[:] = self.data

    # ------------------------------------------------------------------ save --
    def save_as(self):
        if self.dataset is None or self.data is None:
            return
        suggested = self.file_path.with_name(self.file_path.stem + "_edited.nc")
        path, _ = QtWidgets.QFileDialog.getSaveFileName(self, "Save NetCDF copy", str(suggested),
                                                        "NetCDF (*.nc);;All files (*)")
        if not path:
            return
        try:
            if self.regridded:
                self.save_regridded(path)
                QtWidgets.QMessageBox.information(self, "Saved", f"{path}\n\nSource file untouched")
                self.status.setText(f"Saved {path}")
                return
            self.dataset.close()
            shutil.copy2(self.file_path, path)
            with Dataset(path, "r+") as out:
                var = out.variables[self.variable_name]
                to_write = self.data.T if self.transpose else self.data
                fill = getattr(var, "_FillValue", None)
                var[:] = np.where(np.isfinite(to_write), to_write, fill) if fill is not None else to_write
            self.dataset = Dataset(self.file_path, "r")
            QtWidgets.QMessageBox.information(self, "Saved", f"{path}\n\nSource file untouched")
            self.status.setText(f"Saved {path}")
        except Exception as exc:
            self.show_error(exc)
            try:
                self.dataset = Dataset(self.file_path, "r")
            except Exception:
                self.dataset = None

    def closeEvent(self, event):
        self.profile_window.close()
        if self.dataset is not None:
            try:
                self.dataset.close()
            except Exception:
                pass
        event.accept()


