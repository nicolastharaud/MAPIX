    def _polygon_mask(self, poly_ll):
        poly = poly_ll[np.isfinite(poly_ll).all(axis=1)]
        mask = np.zeros(self.data.shape, dtype=bool)
        if poly.shape[0] < 3:
            return mask
        c0, c1 = sorted(int(i) for i in self.lon_ax.idx([poly[:, 0].min(), poly[:, 0].max()]))
        r0, r1 = sorted(int(i) for i in self.lat_ax.idx([poly[:, 1].min(), poly[:, 1].max()]))
        c0, c1 = max(c0 - 1, 0), min(c1 + 1, self.lon.size - 1)
        r0, r1 = max(r0 - 1, 0), min(r1 + 1, self.lat.size - 1)
        LON, LAT = np.meshgrid(self.lon[c0:c1 + 1], self.lat[r0:r1 + 1])
        pts = np.column_stack([LON.ravel(), LAT.ravel()])
        mask[r0:r1 + 1, c0:c1 + 1] = MplPath(poly).contains_points(pts).reshape(LON.shape)
        return mask

    def selection_finished(self, vertices, mode):
        try:
            if len(vertices) < 2 or any(v[0] is None or v[1] is None for v in vertices):
                return
            native = self.proj.native
            if mode in ("rectangle", "ellipse"):
                (x1, y1), (x2, y2) = vertices[:2]
                if mode == "rectangle":
                    poly_xy = densify([(x1, y1), (x2, y1), (x2, y2), (x1, y2)], 60)
                else:
                    cx, cy = (x1 + x2) / 2, (y1 + y2) / 2
                    rx, ry = abs(x2 - x1) / 2, abs(y2 - y1) / 2
                    if rx == 0 or ry == 0:
                        return
                    t = np.linspace(0, 2 * np.pi, 361)
                    poly_xy = np.column_stack([cx + rx * np.cos(t), cy + ry * np.sin(t)])
            else:
                poly_xy = densify(np.asarray(vertices, dtype=float), 60)
            if native:
                poly_ll = poly_xy
            else:
                lo, la = self.proj.inverse(poly_xy[:, 0], poly_xy[:, 1])
                lo = self.lon_min + ((lo - self.lon_min) % 360.0)
                poly_ll = np.column_stack([lo, la])
            if native and mode in ("rectangle", "ellipse"):
                lon_b, lat_b = self.lon[None, :], self.lat[:, None]
                xa, xb = sorted((x1, x2))
                ya, yb = sorted((y1, y2))
                if mode == "rectangle":
                    mask = ((lon_b >= xa) & (lon_b <= xb)) & ((lat_b >= ya) & (lat_b <= yb))
                else:
                    mask = (((lon_b - cx) / rx) ** 2 + ((lat_b - cy) / ry) ** 2) <= 1
            else:
                mask = self._polygon_mask(poly_ll)
            count = int(mask.sum())
            self.selected_mask = mask
            self.outline_ll = poly_ll[np.isfinite(poly_ll).all(axis=1)]
            self.sel_info.setText(f"{count:,}")
            self.zone_value.setValue(0.0)
            self.canvas.set_outline(poly_xy)
            self.set_tool("inspect", quiet=True)
            self.update_enabled()
            self.status.setText(f"{count:,} cells selected   |   Fill, or Detect (Ctrl+D)")
        except Exception as exc:
            self.show_error(exc)

