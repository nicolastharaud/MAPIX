def _dilate(flags, half):
    """Dilatation carrée (rayon `half`) d'un masque booléen."""
    out = flags.copy()
    for s in range(1, half + 1):
        out[s:, :] |= flags[:-s, :]
        out[:-s, :] |= flags[s:, :]
    out2 = out.copy()
    for s in range(1, half + 1):
        out2[:, s:] |= out[:, :-s]
        out2[:, :-s] |= out[:, s:]
    return out2


def detect_outliers(data, mask, threshold, half, mode="both", **kw):
    """
    Repère les cellules de `mask` qui s'écartent de leur voisinage de plus de
    `threshold` (unités de la variable, ici des mètres).

      - mode "high" : crêtes / pics (valeurs trop hautes par rapport aux voisines) ;
      - mode "low"  : fosses / creux (valeurs trop basses) ;
      - mode "both" : les deux.

    Méthode en plusieurs passes, pour qu'une anomalie ne fausse pas la
    référence des cellules saines voisines :
      1. passe à la médiane (points franchement minoritaires dans leur fenêtre) ;
      2. ces points sont retirés des voisinages ;
      3. passes par quartile, qui détectent aussi les anomalies plus larges que
         la moitié de la fenêtre.

    Retourne (masque_aberrant, nombre_d_itérations_max).
    """
    side = _detect_one_side
    want_hi = mode in ("high", "both")
    want_lo = mode in ("low", "both")

    def without(*masks):
        work = data.copy()
        for m in masks:
            work[m] = np.nan
        return work

    # La passe médiane ne sert qu'à nettoyer les voisinages : quelques itérations.
    s_hi, i1 = side(data, mask, threshold, half, "mid_high", max_iter=6, **kw)
    s_lo, i2 = side(data, mask, threshold, half, "mid_low", max_iter=6, **kw)
    removed = s_hi | s_lo
    # Les deux côtés sont toujours analysés (même pour un mode unilatéral) afin
    # que l'anomalie de signe opposé ne fausse pas le résultat.
    hi, i3 = side(without(removed), mask, threshold, half, "high", **kw)
    lo, i4 = side(without(removed, hi), mask, threshold, half, "low", **kw)
    hi2, i5 = side(without(removed, lo), mask, threshold, half, "high", **kw)
    hi = hi | hi2 | s_hi
    lo = lo | s_lo
    result = np.zeros_like(hi)
    if want_hi:
        result |= hi
    if want_lo:
        result |= lo
    return result, max(i1, i2, i3, i4, i5)


def _detect_one_side(data, mask, threshold, half, mode,
                     min_fraction=0.1, max_iter=30):
    """
    Détection d'un seul côté. La valeur de référence d'une cellule est un
    quantile de ses voisines (fenêtre de rayon `half`, cellule exclue) :
    médiane (mid_*), 1er quartile pour les crêtes (high), 3e quartile pour les
    fosses (low). Les quartiles restent fiables même si l'anomalie couvre plus
    de la moitié de la fenêtre.
    Le calcul est ITÉRATIF : les cellules déjà jugées aberrantes sont retirées
    des voisinages, ce qui permet de détecter des anomalies plus larges que la
    fenêtre en les « grignotant » de l'extérieur vers l'intérieur.
    """
    ny, nx = data.shape
    flagged = np.zeros((ny, nx), dtype=bool)
    cand = np.asarray(mask, dtype=bool) & np.isfinite(data)
    if not cand.any():
        return flagged, 0

    pad = half
    padded = np.full((ny + 2 * pad, nx + 2 * pad), np.nan)
    padded[pad:pad + ny, pad:pad + nx] = data
    view = padded[pad:pad + ny, pad:pad + nx]  # vue modifiable des données

    dy, dx = np.meshgrid(np.arange(-half, half + 1), np.arange(-half, half + 1), indexing="ij")
    dy, dx = dy.ravel(), dx.ravel()
    keep = ~((dy == 0) & (dx == 0))
    dy, dx = dy[keep], dx[keep]
    min_n = max(3, int(min_fraction * dy.size))
    quant = {"high": 0.25, "low": 0.75, "mid_high": 0.5, "mid_low": 0.5}[mode]
    chunk = max(500, 3_000_000 // dy.size)

    todo = cand.copy()
    iterations = 0
    for _ in range(max_iter):
        rr, cc = np.nonzero(todo)
        if rr.size == 0:
            break
        iterations += 1
        new = np.zeros((ny, nx), dtype=bool)
        for s in range(0, rr.size, chunk):
            r = rr[s:s + chunk]
            c = cc[s:s + chunk]
            block = padded[(r + pad)[:, None] + dy[None, :], (c + pad)[:, None] + dx[None, :]]
            ok = np.isfinite(block).sum(axis=1) >= min_n
            if not ok.any():
                continue
            with warnings.catch_warnings():
                warnings.simplefilter("ignore", RuntimeWarning)
                ref = np.nanquantile(block[ok], quant, axis=1)
            diff = data[r[ok], c[ok]] - ref
            if mode in ("high", "mid_high"):
                bad = diff > threshold
            else:
                bad = diff < -threshold
            new[r[ok][bad], c[ok][bad]] = True
        if not new.any():
            break
        flagged |= new
        view[new] = np.nan  # on retire les points suspects des voisinages
        todo = cand & ~flagged & _dilate(new, half)
    return flagged, iterations


def interpolate_flagged(data, flagged, lat, lon, k=12, power=2.0):
    """
    Calcule de nouvelles valeurs pour les cellules `flagged` par pondération
    inverse de la distance (IDW) sur les `k` plus proches cellules FIABLES
    (finies et non aberrantes, à l'intérieur comme à l'extérieur de la zone).
    Les distances sont calculées en km (correction de cos(latitude)).

    Retourne (lignes, colonnes, valeurs).
    """
    ny, nx = data.shape
    fr, fc = np.nonzero(flagged)
    if fr.size == 0:
        return fr, fc, np.array([])
    reliable = np.isfinite(data) & ~flagged
    if not reliable.any():
        raise ValueError("Aucun point fiable disponible pour l'interpolation.")

    # Sous-fenêtre autour des points à corriger, élargie jusqu'à contenir
    # assez de points fiables.
    margin = max(10, 2 * k)
    while True:
        r0, r1 = max(0, fr.min() - margin), min(ny, fr.max() + margin + 1)
        c0, c1 = max(0, fc.min() - margin), min(nx, fc.max() + margin + 1)
        sub = reliable[r0:r1, c0:c1]
        full = (r0 == 0 and c0 == 0 and r1 == ny and c1 == nx)
        if sub.sum() >= 4 * k or full:
            break
        margin *= 2
    pr, pc = np.nonzero(sub)
    pr, pc = pr + r0, pc + c0
    k = int(max(1, min(k, pr.size)))

    lat_r = np.deg2rad(lat)

    def to_xy(rows, cols):
        return (EARTH_KM * np.deg2rad(lon[cols]) * np.cos(lat_r[rows]), EARTH_KM * lat_r[rows])

    px, py = to_xy(pr, pc)
    tx, ty = to_xy(fr, fc)
    pz = data[pr, pc]

    if cKDTree is not None:
        dist, idx = cKDTree(np.column_stack([px, py])).query(np.column_stack([tx, ty]), k=k)
        if k == 1:
            dist, idx = dist[:, None], idx[:, None]
    else:
        step = max(1, int(4_000_000 // pr.size))
        dist = np.empty((fr.size, k))
        idx = np.empty((fr.size, k), dtype=int)
        for s in range(0, fr.size, step):
            d2 = (tx[s:s + step, None] - px[None, :]) ** 2 + (ty[s:s + step, None] - py[None, :]) ** 2
            part = np.argpartition(d2, k - 1, axis=1)[:, :k] if k < pr.size else \
                np.tile(np.arange(pr.size), (d2.shape[0], 1))
            idx[s:s + step] = part
            dist[s:s + step] = np.sqrt(np.take_along_axis(d2, part, axis=1))
    w = 1.0 / np.maximum(dist, 1e-6) ** power
    values = (w * pz[idx]).sum(axis=1) / w.sum(axis=1)
    return fr, fc, values


