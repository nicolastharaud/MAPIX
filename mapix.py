class Axis1D:
    """Fast nearest-index lookup on a monotonic 1-D coordinate."""

    def __init__(self, values):
        self.v = np.asarray(values, dtype=float)
        d = np.diff(self.v)
        self.mono = d.size > 0 and (bool(np.all(d > 0)) or bool(np.all(d < 0)))
        self.desc = self.mono and d[0] < 0
        self.s = self.v[::-1] if self.desc else self.v
        self.lo, self.hi = float(self.s[0]), float(self.s[-1])
        self.pad_lo = 0.5 * abs(self.s[1] - self.s[0]) if self.s.size > 1 else 0.5
        self.pad_hi = 0.5 * abs(self.s[-1] - self.s[-2]) if self.s.size > 1 else 0.5

    def contains(self, t):
        return (self.lo - self.pad_lo) <= t <= (self.hi + self.pad_hi)

    def idx(self, t):
        t = np.asarray(t, dtype=float)
        if not self.mono:
            flat = np.atleast_1d(t).ravel()
            out = np.array([int(np.argmin(np.abs(self.v - x))) for x in flat])
            return out.reshape(t.shape) if t.ndim else int(out[0])
        s = self.s
        i = np.searchsorted(s, t)
        i0 = np.clip(i - 1, 0, s.size - 1)
        i1 = np.clip(i, 0, s.size - 1)
        pick = np.where(np.abs(s[i1] - t) < np.abs(s[i0] - t), i1, i0)
        return (s.size - 1 - pick) if self.desc else pick


def is_regular(v):
    v = np.asarray(v, dtype=float)
    if v.size < 3:
        return True
    d = np.diff(v)
    return bool(np.allclose(d, d[0], rtol=1e-3, atol=0))


def densify(pts, n=40, closed=True):
    pts = np.asarray(pts, dtype=float)
    if closed and not np.allclose(pts[0], pts[-1]):
        pts = np.vstack([pts, pts[:1]])
    t = np.linspace(0, 1, n, endpoint=False)[:, None]
    out = [a + (b - a) * t for a, b in zip(pts[:-1], pts[1:])]
    out.append(pts[-1:])
    return np.vstack(out)


def any_decimate(mask, s):
    ny, nx = mask.shape
    m = np.pad(mask, ((0, (-ny) % s), (0, (-nx) % s)))
    return m.reshape(m.shape[0] // s, s, m.shape[1] // s, s).any(axis=(1, 3))


LON_NAMES = {"lon", "lons", "long", "lng", "longitude", "longitudes", "x", "xlon"}
LAT_NAMES = {"lat", "lats", "latitude", "latitudes", "y", "ylat"}


def axis_score(name, var, kind):
    """How likely a 1-D variable is the longitude (kind='lon') or latitude axis."""
    low = name.lower()
    units = str(getattr(var, "units", "")).lower()
    std = str(getattr(var, "standard_name", "")).lower()
    axis = str(getattr(var, "axis", "")).upper()
    score = 0
    if kind == "lon":
        score += 3 * ("degree" in units and "east" in units)
        score += 3 * (std == "longitude")
        score += 1 * (axis == "X")
        names, stem = LON_NAMES, "lon"
    else:
        score += 3 * ("degree" in units and "north" in units)
        score += 3 * (std == "latitude")
        score += 1 * (axis == "Y")
        names, stem = LAT_NAMES, "lat"
    if low in names:
        score += 2
    elif stem in low:
        score += 1
    return score


