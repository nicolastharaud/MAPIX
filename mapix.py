    # --------------------------------------------------------------- history --
    def push_history(self, rows, cols, new_vals, label):
        rows = np.asarray(rows)
        cols = np.asarray(cols)
        old = self.data[rows, cols].copy()
        new = np.broadcast_to(np.asarray(new_vals, dtype=float), old.shape).copy()
        del self.history[self.hist_pos:]
        self.history.append((label, rows.copy(), cols.copy(), old, new))
        if len(self.history) > MAX_HISTORY:
            self.history.pop(0)
        self.hist_pos = len(self.history)
        self.data[rows, cols] = new
        self.after_edit()

    def _step(self, direction):
        if direction < 0 and self.hist_pos > 0:
            self.hist_pos -= 1
            _, r, c, old, _ = self.history[self.hist_pos]
            self.data[r, c] = old
            return True
        if direction > 0 and self.hist_pos < len(self.history):
            _, r, c, _, new = self.history[self.hist_pos]
            self.data[r, c] = new
            self.hist_pos += 1
            return True
        return False

    def undo(self):
        if self.data is not None and self._step(-1):
            self.after_edit()
            self.status.setText("Undo")

    def redo(self):
        if self.data is not None and self._step(+1):
            self.after_edit()
            self.status.setText("Redo")

    def goto_history(self, k):
        if self.data is None:
            return
        while self.hist_pos > k and self._step(-1):
            pass
        while self.hist_pos < k and self._step(+1):
            pass
        self.after_edit()

    def refresh_history(self):
        self.hist_list.blockSignals(True)
        self.hist_list.clear()
        self.hist_list.addItem("0  Original")
        for i, h in enumerate(self.history, 1):
            self.hist_list.addItem(f"{i}  {h[0]}")
        for i in range(self.hist_list.count()):
            it = self.hist_list.item(i)
            if i > self.hist_pos:
                f = it.font()
                f.setItalic(True)
                it.setFont(f)
                it.setForeground(QtGui.QBrush(QtGui.QColor("#888888")))
        self.hist_list.setCurrentRow(self.hist_pos)
        self.hist_list.blockSignals(False)

