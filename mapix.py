def regrid_array(data, lon, lat, lon_new, lat_new, method, progress=None):
    """Resample `data` (lat, lon) onto lon_new/lat_new. method: 'nearest' or 'bilinear'."""
    lon = np.asarray(lon, dtype=float)
    lat = np.asarray(lat, dtype=float)
    src = data
    if lon[0] > lon[-1]:
        lon, src = lon[::-1], src[:, ::-1]
    if lat[0] > lat[-1]:
        lat, src = lat[::-1], src[::-1, :]
    ny, nx = lat_new.size, lon_new.size
    out = np.empty((ny, nx), dtype=np.float64)
    chunk = max(1, int(2_000_000 // max(nx, 1)))
    starts = list(range(0, ny, chunk))
    if method == "nearest":
        cols = np.asarray(Axis1D(lon).idx(lon_new), dtype=int)
        rows = np.asarray(Axis1D(lat).idx(lat_new), dtype=int)
    else:
        def lin(s, t):
            i1 = np.clip(np.searchsorted(s, t), 1, s.size - 1)
            i0 = i1 - 1
            w = np.clip((t - s[i0]) / (s[i1] - s[i0]), 0.0, 1.0)
            return i0, i1, w
        c0, c1, wx = lin(lon, lon_new)
        r0, r1, wy = lin(lat, lat_new)
    for k, s in enumerate(starts):
        sl = slice(s, s + chunk)
        if method == "nearest":
            out[sl] = src[rows[sl]][:, cols]
        else:
            a, b = src[r0[sl]], src[r1[sl]]
            v0 = a[:, c0] * (1 - wx) + a[:, c1] * wx
            v1 = b[:, c0] * (1 - wx) + b[:, c1] * wx
            wyc = wy[sl][:, None]
            out[sl] = v0 * (1 - wyc) + v1 * wyc
        if progress:
            progress(k, len(starts))
    return out


